// Architecture page screenshots, one per tab plus a selected part: node scripts/spikes/arch-shots.mjs <baseUrl> <outDir>
import { chromium } from "@playwright/test";
const [base, out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: `${process.env.HOME}/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome` });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text().slice(0, 200)));
await page.goto(`${base}/architecture`, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/arch-map.png` });
await page.getByRole("button", { name: "Rescue agent: open details" }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/arch-node.png` });
await page.getByRole("button", { name: "Journeys" }).click();
await page.waitForTimeout(2600 * 4 + 600);
await page.screenshot({ path: `${out}/arch-journey.png` });
await page.getByRole("button", { name: "Trust" }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/arch-trust.png` });
await page.getByRole("button", { name: "Decisions" }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/arch-decisions.png` });
const phone = await browser.newPage({ viewport: { width: 390, height: 844 } });
await phone.goto(`${base}/architecture`, { waitUntil: "networkidle" });
await phone.waitForTimeout(1000);
await phone.screenshot({ path: `${out}/arch-phone.png` });
console.log(JSON.stringify({ errors }));
await browser.close();
